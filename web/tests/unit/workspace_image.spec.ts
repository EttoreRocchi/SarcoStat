import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import { describe, expect, it } from "vitest";

import { WEB_DIR } from "../../scripts/lane.mjs";
import { readImageHeader } from "../../src/io/files.ts";
import { pngHeader } from "../../src/io/image/decode.ts";
import { jpegOrientations, pngExifChunks, storedGrid } from "../../src/io/image/exif.ts";
import { pythonExecutable } from "./worker_mock.ts";

const IMAGES = path.join(WEB_DIR, "tests", "fixtures", "images");
const GENERATOR = path.join(WEB_DIR, "scripts", "make_image_fixtures.py");

interface Entry {
  kind: string;
  width: number;
  height: number;
  bit_depth: number;
  orientation: number | null;
  sha256: string;
  pixels: string;
  mode: string;
}

function manifest(dir = IMAGES): { pillow: string; images: Record<string, Entry> } {
  return JSON.parse(fs.readFileSync(path.join(dir, "manifest.json"), "utf8")) as { pillow: string; images: Record<string, Entry> };
}

function read(name: string): Uint8Array {
  return new Uint8Array(fs.readFileSync(path.join(IMAGES, name)));
}

function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) {
      crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1;
    }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Uint8Array): Uint8Array {
  const body = new Uint8Array([...Buffer.from(type, "latin1"), ...data]);
  const out = Buffer.alloc(12 + data.length);
  out.writeUInt32BE(data.length, 0);
  out.set(body, 4);
  out.writeUInt32BE(crc32(body), 8 + data.length);
  return new Uint8Array(out);
}

function tiff(order: "II" | "MM", orientation: number): Uint8Array {
  const out = Buffer.alloc(26);
  const little = order === "II";
  out.write(order, 0, "latin1");
  const u16 = (value: number, at: number): void => void (little ? out.writeUInt16LE(value, at) : out.writeUInt16BE(value, at));
  const u32 = (value: number, at: number): void => void (little ? out.writeUInt32LE(value, at) : out.writeUInt32BE(value, at));
  u16(42, 2);
  u32(8, 4);
  u16(1, 8);
  u16(0x0112, 10);
  u16(3, 12);
  u32(1, 14);
  u16(orientation, 18);
  u32(0, 22);
  return new Uint8Array(out);
}

function jpegWithExif(order: "II" | "MM", orientation: number): Uint8Array {
  const exif = new Uint8Array([0x45, 0x78, 0x69, 0x66, 0, 0, ...tiff(order, orientation)]);
  const app1 = [0xff, 0xe1, (exif.length + 2) >> 8, (exif.length + 2) & 0xff, ...exif];
  const sof = [0xff, 0xc0, 0, 11, 8, 0, 24, 0, 40, 1, 1, 0x11, 0];
  return new Uint8Array([0xff, 0xd8, 0xff, 0xe0, 0, 4, 0, 0, ...app1, ...sof, 0xff, 0xd9]);
}

describe("image fixtures", () => {
  const images = manifest().images;

  it("hold the sizes, bit depths and SHA-256 of their manifest", () => {
    expect(Object.keys(images).sort()).toEqual([
      "grey_32x40.png",
      "grey_64x48.png",
      "jpeg_grey_o1_40x24.jpg",
      "jpeg_grey_o6_40x24.jpg",
      "marked_61x47.png",
      "png_grey16_33x21.png",
      "png_grey8_37x29.png",
      "png_rgb8_31x22.png",
    ]);
    for (const [name, entry] of Object.entries(images)) {
      const bytes = read(name);
      expect(crypto.createHash("sha256").update(bytes).digest("hex"), name).toBe(entry.sha256);
      expect(readImageHeader(bytes), name).toEqual({ kind: entry.kind, width: entry.width, height: entry.height });
      expect(Buffer.from(entry.pixels, "base64").length, name).toBe(entry.width * entry.height * (entry.mode === "RGB" ? 3 : entry.mode === "I;16" ? 2 : 1));
      if (entry.kind === "png") {
        expect(pngHeader(bytes)?.bitDepth, name).toBe(entry.bit_depth);
      }
    }
  });

  it(`are regenerated byte for byte by make_image_fixtures.py (${pythonExecutable()})`, () => {
    const out = fs.mkdtempSync(path.join(os.tmpdir(), "sarcostat-fixtures-"));
    try {
      execFileSync(pythonExecutable(), [GENERATOR, out], { encoding: "utf8", env: { ...process.env, PYTHONDONTWRITEBYTECODE: "1" } });
      const fresh = manifest(out);
      const samePillow = fresh.pillow === manifest().pillow;
      for (const name of [...Object.keys(images), "manifest.json"]) {
        const same = Buffer.compare(fs.readFileSync(path.join(out, name)), fs.readFileSync(path.join(IMAGES, name))) === 0;
        if (samePillow || name.startsWith("grey_")) {
          expect(same, name).toBe(true);
        }
      }
      for (const [name, entry] of Object.entries(fresh.images)) {
        expect({ ...entry, sha256: "" }, name).toEqual({ ...images[name], sha256: "" });
      }
    } finally {
      fs.rmSync(out, { recursive: true, force: true });
    }
  });
});

describe("EXIF orientation", () => {
  it("is patched to 1 in a byte copy of a JPEG, so the decoder gives the stored grid", () => {
    const original = read("jpeg_grey_o6_40x24.jpg");
    const before = Buffer.from(original);
    const grid = storedGrid(original, "jpeg");
    expect(grid.orientation).toBe(6);
    expect(grid.changed).toBe(true);
    expect(grid.bytes).not.toBe(original);
    expect(Buffer.compare(Buffer.from(original), before)).toBe(0);
    expect(jpegOrientations(grid.bytes).map((entry) => entry.value)).toEqual([1]);
    const differing = [...grid.bytes].map((value, i) => (value === original[i] ? -1 : i)).filter((i) => i >= 0);
    expect(differing).toHaveLength(1);
    expect(grid.bytes.length).toBe(original.length);
  });

  it("leaves a JPEG with orientation 1 and a PNG without eXIf untouched", () => {
    const upright = read("jpeg_grey_o1_40x24.jpg");
    expect(storedGrid(upright, "jpeg")).toEqual({ bytes: upright, orientation: 1, changed: false });
    const png = read("png_grey8_37x29.png");
    expect(storedGrid(png, "png")).toEqual({ bytes: png, orientation: null, changed: false });
  });

  it("is found and patched in big- and little-endian EXIF", () => {
    for (const order of ["II", "MM"] as const) {
      for (const value of [3, 6, 8]) {
        const bytes = jpegWithExif(order, value);
        expect(jpegOrientations(bytes).map((entry) => [entry.value, entry.little])).toEqual([[value, order === "II"]]);
        const grid = storedGrid(bytes, "jpeg");
        expect(jpegOrientations(grid.bytes).map((entry) => entry.value)).toEqual([1]);
        expect(readImageHeader(grid.bytes)).toEqual({ kind: "jpeg", width: 40, height: 24 });
      }
    }
  });

  it("is dropped from a PNG with its eXIf chunk, leaving the other chunks byte for byte", () => {
    const png = read("png_grey8_37x29.png");
    const exif = chunk("eXIf", tiff("MM", 6));
    const tagged = new Uint8Array([...png.subarray(0, 33), ...exif, ...png.subarray(33)]);
    expect(pngExifChunks(tagged).map((entry) => entry.orientation)).toEqual([6]);
    const grid = storedGrid(tagged, "png");
    expect(grid.orientation).toBe(6);
    expect(Buffer.compare(Buffer.from(grid.bytes), Buffer.from(png))).toBe(0);
  });

  it("does not read past truncated or foreign data", () => {
    expect(jpegOrientations(new Uint8Array([0xff, 0xd8, 0xff, 0xe1, 0x00]))).toEqual([]);
    expect(jpegOrientations(new Uint8Array([1, 2, 3]))).toEqual([]);
    const truncated = jpegWithExif("II", 6).subarray(0, 30);
    expect(jpegOrientations(truncated)).toEqual([]);
    expect(pngExifChunks(read("png_grey8_37x29.png").subarray(0, 40))).toEqual([]);
  });
});
